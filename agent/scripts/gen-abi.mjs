#!/usr/bin/env node
// Generates src/abi/generated.ts from the frozen Solidity interfaces in
// contracts/src/interfaces/, so the agent never hand-copies an ABI.
//
//   npm run abi         regenerate the file
//   npm run abi:check   exit 1 if the committed file is out of date
//
// Uses solc-js pinned to 0.8.28, the compiler that produced
// contracts/abi/frozen-signatures.txt.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import solc from "solc";

const here = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(here, "../..");
const interfacesDir = "contracts/src/interfaces";
const outFile = path.resolve(here, "../src/abi/generated.ts");

// Interface name -> exported constant name.
const EXPORTS = {
  ILeashVault: "leashVaultAbi",
  ILeashVaultFactory: "leashVaultFactoryAbi",
  IPriceFeed: "priceFeedAbi",
  IFaucetToken: "faucetTokenAbi",
};

const sources = {};
for (const file of readdirSync(path.join(repoRoot, interfacesDir)).filter((f) => f.endsWith(".sol")).sort()) {
  sources[`${interfacesDir}/${file}`] = { content: readFileSync(path.join(repoRoot, interfacesDir, file), "utf8") };
}

const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: "Solidity",
      sources,
      settings: { outputSelection: { "*": { "*": ["abi"] } } },
    }),
  ),
);

const errors = (output.errors ?? []).filter((e) => e.severity === "error");
if (errors.length > 0) {
  for (const e of errors) console.error(e.formattedMessage);
  process.exit(1);
}

let ts =
  "// GENERATED by agent/scripts/gen-abi.mjs from contracts/src/interfaces/*.sol (solc " +
  solc.version().split("+")[0] +
  ").\n// Do not edit by hand: run `npm run abi` after an approved ABI change.\n\n";

for (const [contract, exportName] of Object.entries(EXPORTS)) {
  const unit = Object.keys(output.contracts ?? {}).find((name) => output.contracts[name][contract]);
  if (!unit) {
    console.error(`gen-abi: ${contract} not found in ${interfacesDir}`);
    process.exit(1);
  }
  ts += `export const ${exportName} = ${JSON.stringify(output.contracts[unit][contract].abi, null, 2)} as const;\n\n`;
}

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(outFile, "utf8");
  } catch {
    // missing file counts as out of date
  }
  if (current !== ts) {
    console.error("gen-abi: src/abi/generated.ts is out of date. Run `npm run abi`.");
    process.exit(1);
  }
  console.log("gen-abi: src/abi/generated.ts is up to date");
} else {
  writeFileSync(outFile, ts);
  console.log(`gen-abi: wrote ${path.relative(repoRoot, outFile)}`);
}
